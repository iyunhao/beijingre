const pad = (n) => String(n).padStart(2, '0');

/** 展开成 { 'YYYY-MM-DD': n }（仅含表内有值的日） */
function expand() {
  const out = {};
  for (const [ci, month] of COLS.entries()) {
    for (let r = 0; r < ROWS.length; r++) {
      const v = ROWS[r][ci];
      if (v == null) continue;
      out[`${month}-${pad(r + 1)}`] = v;
    }
  }
  return out;
}

/** 各月实际合计（逐行求和），应与 OFFICIAL_MONTH_TOTAL 完全一致 */
function computedTotals() {
  const t = {};
  for (const [k, v] of Object.entries(expand())) {
    const m = k.slice(0, 7);
    t[m] = (t[m] || 0) + v;
  }
  return t;
}

